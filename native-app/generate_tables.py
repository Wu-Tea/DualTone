"""Build-time only: freeze the proven causal resampling filters for native DSP."""
import sys
from pathlib import Path
root=Path(__file__).resolve().parent.parent
sys.path[:0]=[str(root),str(root/'lib')]
from resampling import rate_filter
from config import SUPPORTED_DEVICE_RATES_HZ
lines=['// Generated by generate_tables.py; runtime does not depend on Python.',
       '#pragma once','namespace dt {',
       'struct ResampleTable {int source,target,up,down;const double* taps;size_t count;};']
rows=[]
for rate in SUPPORTED_DEVICE_RATES_HZ:
    if rate==48000:continue
    for source,target in ((rate,48000),(48000,rate)):
        up,down,taps=rate_filter(source,target)
        name=f'taps_{source}_{target}'
        lines.append(f'inline constexpr double {name}[]={{'+','.join(format(float(v),'.17g') for v in taps)+'};')
        rows.append(f'{{{source},{target},{up},{down},{name},{len(taps)}}}')
lines+=['inline constexpr ResampleTable resample_tables[]={'+','.join(rows)+'};','}']
(root/'native-app/resampler_tables.hpp').write_text('\n'.join(lines),encoding='utf-8')

# One list drives endpoint validation and the coefficient generator.
rate_header = ['// Generated by generate_tables.py from config.SUPPORTED_DEVICE_RATES_HZ.',
               '#pragma once', '#include <array>', 'namespace dt {',
               f'inline constexpr std::array<int, {len(SUPPORTED_DEVICE_RATES_HZ)}> DeviceRates = {{' + ','.join(map(str,SUPPORTED_DEVICE_RATES_HZ)) + '};', '}']
(root/'native-app/device_rates.hpp').write_text('\n'.join(rate_header)+'\n',encoding='utf-8')
